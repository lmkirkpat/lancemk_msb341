// mentor/curriculum/skills-built.json tells the panel which path skills are built and which have a
// review (spec 007 PN-16, plan P2). It's generated from the tool files, and these tests fail when it
// has fallen behind them.

import { test } from "node:test";
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HOME = fs.mkdtempSync(path.join(os.tmpdir(), "skills-built-"));
process.env.AE_MENTOR_HOME = HOME;
delete process.env.AE_MENTOR_TOOLS_DIR;

const { discover } = await import("../tools/index.mjs");
const { buildSkillsBuilt, renderSkillsBuilt } = await import("../scripts/write-skills-built.mjs");

const MENTOR = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const DATA_FILE = path.join(MENTOR, "curriculum", "skills-built.json");
const SCRIPT = path.join(MENTOR, "scripts", "write-skills-built.mjs");
const PATH_ORDER = JSON.parse(fs.readFileSync(path.join(MENTOR, "curriculum", "path.json"), "utf8")).skills.map((s) => s.id);
const ABOUT = "Generated by mentor/scripts/write-skills-built.mjs from mentor/tools. Don't edit.";

test("the committed file matches what the tool files say now", async () => {
  const { SKILLS, FINDERS } = await discover([path.join(MENTOR, "tools")]);
  assert.equal(
    fs.readFileSync(DATA_FILE, "utf8"),
    renderSkillsBuilt(buildSkillsBuilt({ skills: SKILLS, finders: FINDERS })),
    "skills-built.json is out of date: run node mentor/scripts/write-skills-built.mjs",
  );
});

test("the committed file has the shape the panel reads", () => {
  const data = JSON.parse(fs.readFileSync(DATA_FILE, "utf8"));
  assert.deepEqual(Object.keys(data), ["about", "skills"]);
  assert.equal(data.about, ABOUT);
  assert.deepEqual(data.skills, {
    "easing.basic": { review: false },
    "keyframes.types": { review: true },
    "easing.speed_graph": { review: true },
    "timing.offset": { review: true },
    "transform.anchor": { review: true },
    "parenting.null": { review: true },
  });
});

test("every built skill is on the path, in path order", () => {
  const ids = Object.keys(JSON.parse(fs.readFileSync(DATA_FILE, "utf8")).skills);
  assert.deepEqual(ids, PATH_ORDER.filter((id) => ids.includes(id)));
});

test("review comes only from a finder that says exactly true", () => {
  const { skills } = buildSkillsBuilt({
    skills: ["a", "b", "c", "d"],
    finders: { a: { review: true }, b: { review: false }, c: { review: "yes" } },
  });
  assert.deepEqual(skills, { a: { review: true }, b: { review: false }, c: { review: false }, d: { review: false } });
});

test("a skill that isn't declared is left out, even if the path lists it", () => {
  const { skills } = buildSkillsBuilt({ skills: ["easing.basic"], finders: {} });
  assert.deepEqual(Object.keys(skills), ["easing.basic"]);
});

test("a new skill not yet on the path still appears, after the path's skills", () => {
  const { skills } = buildSkillsBuilt({ skills: ["zz.new", "aa.new", "timing.offset", "easing.basic"], finders: {} });
  assert.deepEqual(Object.keys(skills), ["easing.basic", "timing.offset", "aa.new", "zz.new"]);
});

test("the output is stable and ends in a newline", () => {
  const input = { skills: ["timing.offset", "easing.basic"], finders: {} };
  const reversed = { skills: ["easing.basic", "timing.offset"], finders: {} };
  const text = renderSkillsBuilt(buildSkillsBuilt(input));
  assert.equal(text, renderSkillsBuilt(buildSkillsBuilt(reversed)));
  assert.ok(text.endsWith("}\n"));
});

test("running the script writes the file it was pointed at, and leaves the real one alone", () => {
  const out = path.join(HOME, "out", "skills-built.json");
  fs.mkdirSync(path.dirname(out));
  const before = fs.statSync(DATA_FILE).mtimeMs;
  // A tools folder set for a test must not change what the generator reads.
  const env = { ...process.env, AE_MENTOR_HOME: HOME, AE_MENTOR_TOOLS_DIR: path.join(HOME, "out") };
  execFileSync(process.execPath, [SCRIPT, out], { env });
  assert.equal(fs.readFileSync(out, "utf8"), fs.readFileSync(DATA_FILE, "utf8"));
  assert.equal(fs.statSync(DATA_FILE).mtimeMs, before);
});
