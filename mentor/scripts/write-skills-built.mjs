// Writes mentor/curriculum/skills-built.json: which path skills are built and which have a review
// (spec 007 PN-16, plan P2). The panel reads the file so it doesn't have to load the tool code.
//
// Run after adding a skill or changing a finder's review flag:
//   node mentor/scripts/write-skills-built.mjs
// mentor/test/skills-built.test.mjs fails until the file is current. An argument writes elsewhere.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { discover } from "../tools/index.mjs";

const SCRIPT = fileURLToPath(import.meta.url);
const MENTOR = path.join(path.dirname(SCRIPT), "..");
const CURRICULUM = path.join(MENTOR, "curriculum");
const ABOUT = "Generated by mentor/scripts/write-skills-built.mjs from mentor/tools. Don't edit.";

function pathOrder() {
  return JSON.parse(fs.readFileSync(path.join(CURRICULUM, "path.json"), "utf8")).skills.map((s) => s.id);
}

// Built skills in path order; any not on the path yet go last, by name, so the file never depends on
// the order the tool files load in.
export function buildSkillsBuilt({ skills, finders = {} }) {
  const order = pathOrder();
  const onPath = order.filter((id) => skills.includes(id));
  const offPath = skills.filter((id) => !order.includes(id)).sort();
  const entries = [...onPath, ...offPath].map((id) => [id, { review: finders[id]?.review === true }]);
  return { about: ABOUT, skills: Object.fromEntries(entries) };
}

export function renderSkillsBuilt(data) {
  return JSON.stringify(data, null, 2) + "\n";
}

if (process.argv[1] && fs.realpathSync(process.argv[1]) === SCRIPT) {
  // Named directly, so AE_MENTOR_TOOLS_DIR (test-only) can't change what gets generated.
  const { SKILLS, FINDERS } = await discover([path.join(MENTOR, "tools")]);
  const out = process.argv[2] || path.join(CURRICULUM, "skills-built.json");
  fs.writeFileSync(out, renderSkillsBuilt(buildSkillsBuilt({ skills: SKILLS, finders: FINDERS })));
}
